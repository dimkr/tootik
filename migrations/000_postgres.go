// canonicalID returns the expression that computes the canonical ID (see [ap.Canonical]) of a column holding an ID.
func canonicalID(id string) string {
	start := fmt.Sprintf("9 + strpos(substr(%s, 9), '/') + 22", id)
	return strings.NewReplacer("$ID", id, "$START", start).Replace(
		`CASE
			WHEN $ID ILIKE 'https://%' AND ($ID ILIKE '%/.well-known/apgateway/did:key:z6Mk%' OR $ID ILIKE '%/.well-known/apgateway/did:key:ukC%') THEN
				'ap://' || substr($ID, $START, CASE WHEN strpos(substr($ID, $START), '?') > 0 THEN strpos(substr($ID, $START), '?') - 1 ELSE length($ID) END)
			WHEN $ID ILIKE 'https://%' THEN $ID
			ELSE NULL
		END`,
	)
}

